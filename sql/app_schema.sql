-- Schema for application data (PostgreSQL 16): the agent's query log.
-- Design notes: docs/SCHEMA.md, "App schema and logger role".
--
-- Safe to run many times and never deletes log rows: every statement is
-- CREATE ... IF NOT EXISTS or COMMENT. A later column change needs an explicit
-- ALTER TABLE, because CREATE TABLE IF NOT EXISTS leaves an existing table as it is.
--
-- Kept out of schema public, so recreating the numeric tables (DROP SCHEMA public
-- CASCADE) does not touch the log, and the Text-to-SQL schema context (public only)
-- never shows it. Privileges are set in sql/roles.sql: run
-- `python -m vnmacro.roles apply` after this file.

CREATE SCHEMA IF NOT EXISTS app;

COMMENT ON SCHEMA app IS
    'Application data (query log). Not exposed to the Text-to-SQL tool, which only sees the numeric tables in schema public.';

-- ---------------------------------------------------------------------------
-- app.query_log
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app.query_log (
    id                   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    run_id               UUID NOT NULL UNIQUE,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    component            TEXT NOT NULL,
    question             TEXT NOT NULL,
    model                TEXT,
    prompt_version       TEXT,
    status               TEXT NOT NULL
                         CHECK (status IN ('ok', 'cannot_answer', 'blocked', 'error')),
    final_sql            TEXT,
    attempts             INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    sql_attempts         JSONB NOT NULL DEFAULT '[]'
                         CHECK (jsonb_typeof(sql_attempts) = 'array'),
    error                TEXT,
    row_count            INTEGER CHECK (row_count >= 0),
    latency_ms           INTEGER CHECK (latency_ms >= 0),
    input_tokens         INTEGER CHECK (input_tokens >= 0),
    cached_input_tokens  INTEGER CHECK (cached_input_tokens >= 0),
    output_tokens        INTEGER CHECK (output_tokens >= 0),
    cost_usd             NUMERIC(12, 6) CHECK (cost_usd >= 0),
    CHECK (cached_input_tokens <= input_tokens),
    CHECK (status <> 'ok' OR final_sql IS NOT NULL),
    CHECK (status <> 'error' OR error IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS query_log_created_at_idx ON app.query_log (created_at);

COMMENT ON TABLE app.query_log IS
    'One row per question handled by an agent component (e.g. one Text-to-SQL request, with all its LLM attempts). Written by vnmacro_logger (INSERT only); read by the owner for evaluation and cost tracking.';
COMMENT ON COLUMN app.query_log.id IS
    'Row id, generated by the database.';
COMMENT ON COLUMN app.query_log.run_id IS
    'Id of the run, made by the Python code with uuid4 before the INSERT (not by the database): vnmacro_logger cannot read the table, so INSERT ... RETURNING id is not allowed and the code must know the key in advance. User feedback (thumbs up/down, Phase 7) will refer to this run_id.';
COMMENT ON COLUMN app.query_log.created_at IS
    'Time the row was written (end of the request).';
COMMENT ON COLUMN app.query_log.component IS
    'Component that handled the request, e.g. ''text_to_sql''.';
COMMENT ON COLUMN app.query_log.question IS
    'User question as received (Vietnamese text). May hold personal data: only the owner can read it.';
COMMENT ON COLUMN app.query_log.model IS
    'LLM model id used, e.g. ''gpt-6-luna''; NULL if no LLM was called.';
COMMENT ON COLUMN app.query_log.prompt_version IS
    'Short hash of the fixed prompt material sent to the LLM (schema context + SQL conventions + examples). Same hash = same prompt prefix.';
COMMENT ON COLUMN app.query_log.status IS
    '''ok'' (SQL ran), ''cannot_answer'' (LLM said SQL cannot answer), ''blocked'' (SQL check rejected every attempt), ''error'' (LLM, database or code error).';
COMMENT ON COLUMN app.query_log.final_sql IS
    'SQL that was run for the answer; required when status = ''ok''.';
COMMENT ON COLUMN app.query_log.attempts IS
    'Number of LLM calls made for this request (first try + retries).';
COMMENT ON COLUMN app.query_log.sql_attempts IS
    'JSON array, one object per attempt in order: the SQL tried and the check or database error, if any.';
COMMENT ON COLUMN app.query_log.error IS
    'Final error message; required when status = ''error''.';
COMMENT ON COLUMN app.query_log.row_count IS
    'Rows returned by final_sql; NULL if it did not run.';
COMMENT ON COLUMN app.query_log.latency_ms IS
    'Wall time of the whole request in milliseconds (LLM calls + checks + query).';
COMMENT ON COLUMN app.query_log.input_tokens IS
    'Total input tokens over all LLM calls, including cached ones.';
COMMENT ON COLUMN app.query_log.cached_input_tokens IS
    'Part of input_tokens served from the provider prompt cache.';
COMMENT ON COLUMN app.query_log.output_tokens IS
    'Total output tokens over all LLM calls (including reasoning tokens, if any).';
COMMENT ON COLUMN app.query_log.cost_usd IS
    'Estimated cost in USD of all LLM calls, from token counts and the configured prices.';
